-- =====================================================
-- Migration: Períodos de MO extra por aviso (regidos pela janela de
--            visualização — view_start_date / view_end_date)
-- Date: 2026-10-19
-- Description: Separa a disponibilidade de mão de obra extra em
--              PERÍODOS dentro da JANELA DE VISUALIZAÇÃO de um aviso
--              (cfg_app_notices). A vigência (start_date/end_date) só
--              define a validade do aviso; o lançamento segue a janela.
--
--              Modelo: períodos nascem dos lançamentos.
--              - 1º lançamento da notice cria um período aberto
--                (period_end = NULL) com period_start = instante do
--                lançamento (horário de São Paulo). O período nunca
--                começa antes da janela.
--              - Lançamento no mesmo dia do período aberto edita o
--                lançamento dentro do período atual
--                (cfg_app_notices_workers).
--              - Lançamento em outro dia fecha o aberto no instante do
--                lançamento e abre um novo; os dias sem lançamento
--                "carregam" a escala anterior (períodos contínuos).
--              - O último período aberto vale até a view_end_date da
--                notice (leitura usa COALESCE(period_end, view_end_date);
--                trigger abaixo limita períodos quando view_end_date é
--                alterada; bloqueia a gravação de lançamento fora da
--                janela — ver AppNoticesWorkersService).
--
--              Histórico: lançamentos existentes (sem período) ficam em
--              UM período por notice cobrindo a janela de visualização
--              vigente — totais por dia preservados, sem dobrar agregados.
--
--              RESTRIÇÕES:
--              - uq_notice_workers_period_open (parcial, period_end IS NULL):
--                garante um único período aberto por notice (corrida na
--                virada de dia; o app faz retry em conflito 23505).
--              - uq_cfg_app_notices_workers passa a incluir workers_period_id.
--
--              Aplicar manualmente no SQL Editor do Supabase.
--              Idempotente (seguro para reexecutar).
-- =====================================================

-- 1. Tabela de períodos ------------------------------------------------
CREATE TABLE IF NOT EXISTS public.cfg_app_notices_workers_periods (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    notice_id        integer NOT NULL
                          REFERENCES public.cfg_app_notices(id) ON DELETE CASCADE,
    label            varchar(80) NOT NULL,
    period_start     timestamp WITHOUT time zone NOT NULL,
    period_end       timestamp WITHOUT time zone,  -- NULL = período em aberto (vigente)
    position_index   integer NOT NULL DEFAULT 0,
    created_at       timestamptz NOT NULL DEFAULT now(),
    updated_at       timestamptz NOT NULL DEFAULT now(),
    created_user_id  bigint,
    updated_user_id  bigint,
    CONSTRAINT chk_notice_workers_period_dates
        CHECK (period_end IS NULL OR period_end > period_start),
    CONSTRAINT uq_cfg_app_notices_workers_periods
        UNIQUE (notice_id, label)
);

COMMENT ON TABLE public.cfg_app_notices_workers_periods IS
    'Períodos automáticos de MO extra dentro da janela de visualização de um aviso; period_end NULL = período vigente';
COMMENT ON COLUMN public.cfg_app_notices_workers_periods.period_start IS
    'Início do período (horário de São Paulo, sem fuso) - 1º período começa no instante do 1º lançamento';
COMMENT ON COLUMN public.cfg_app_notices_workers_periods.period_end IS
    'Fim do período (horário de São Paulo). NULL indica período em aberto, válido até a view_end_date do aviso';

-- Um único período em aberto por notice (neutraliza corrida da virada de dia;
-- a gravação no app faz retry em conflito 23505 e reusa o período que venceu)
CREATE UNIQUE INDEX IF NOT EXISTS uq_notice_workers_period_open
    ON public.cfg_app_notices_workers_periods(notice_id)
    WHERE period_end IS NULL;

-- 2. Coluna do lançamento → período ------------------------------------
--    Coluna opcional durante a migração (idempotente: NOT NULL é aplicado
--    apenas na etapa 4, após os registros antigos receberem período).
ALTER TABLE public.cfg_app_notices_workers
    ADD COLUMN IF NOT EXISTS workers_period_id bigint;

-- 2b) FK da coluna para os períodos. OBRIGATÓRIA: além da integridade,
--     o PostgREST só consegue embutir `cfg_app_notices_workers_periods` no
--     select do app se a foreign key existir no schema cache. Sem ela a
--     query retorna PGRST200 ("Could not find a relationship between
--     'cfg_app_notices_workers' and 'cfg_app_notices_workers_periods'").
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'fk_cfg_app_notices_workers_period'
          AND conrelid = 'public.cfg_app_notices_workers'::regclass
    ) THEN
        ALTER TABLE public.cfg_app_notices_workers
            ADD CONSTRAINT fk_cfg_app_notices_workers_period
            FOREIGN KEY (workers_period_id)
            REFERENCES public.cfg_app_notices_workers_periods(id)
            ON DELETE CASCADE;
    END IF;
END $$;

-- 3. Histórico: um período cobrindo a janela de visualização vigente -----
--    Atenção: a janela de visualização pode ser anterior/ posterior à
--    vigência em avisos futuros/passados. O período de histórico cobre
--    view_start_date..view_end_date para preservar totais por dia.
INSERT INTO public.cfg_app_notices_workers_periods
    (notice_id, label, period_start, period_end, position_index)
SELECT n.id,
       'Janela de visualização completa (histórico)',
       n.view_start_date,
       n.view_end_date,
       0
FROM public.cfg_app_notices n
WHERE EXISTS (
        SELECT 1 FROM public.cfg_app_notices_workers w
        WHERE w.notice_id = n.id AND w.workers_period_id IS NULL
      )
  AND NOT EXISTS (
        SELECT 1 FROM public.cfg_app_notices_workers_periods p
        WHERE p.notice_id = n.id
      );

-- Lançamentos antigos → período do histórico da sua notice
UPDATE public.cfg_app_notices_workers w
SET workers_period_id = p.id
FROM public.cfg_app_notices_workers_periods p
WHERE p.notice_id = w.notice_id
  AND p.label = 'Janela de visualização completa (histórico)'
  AND w.workers_period_id IS NULL;

-- 4. Chave única passa a incluir o período ------------------------------
--    Conferência de dependentes antes do drop (AGENTS.md): nenhuma view
--    da base referencia uq_cfg_app_notices_workers (conferido em dev/).
ALTER TABLE public.cfg_app_notices_workers
    DROP CONSTRAINT IF EXISTS uq_cfg_app_notices_workers;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'uq_cfg_app_notices_workers'
          AND conrelid = 'public.cfg_app_notices_workers'::regclass
    ) THEN
        ALTER TABLE public.cfg_app_notices_workers
            ADD CONSTRAINT uq_cfg_app_notices_workers
            UNIQUE (notice_id, unit_id, company_id, workers_period_id);
    END IF;
END $$;

-- NOT NULL somente agora, com todo o histórico apontado
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'public'
          AND table_name = 'cfg_app_notices_workers'
          AND column_name = 'workers_period_id'
          AND is_nullable = 'NO'
    ) THEN
        ALTER TABLE public.cfg_app_notices_workers
            ALTER COLUMN workers_period_id SET NOT NULL;
    END IF;
END $$;

-- 5. Trigger: view_end_date do aviso limita os períodos ------------------
--    Ao alterar view_end_date (antecipar ou prorrogar), períodos em aberto
--    ou encerrados além do novo fim são agrupados para o novo fim.
--    Períodos que começam após o novo view_end_date são deixados como estão
--    (não há exclusão de histórico).
CREATE OR REPLACE FUNCTION public.cfg_app_notices_limit_workers_periods()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.view_end_date IS DISTINCT FROM OLD.view_end_date THEN
        UPDATE public.cfg_app_notices_workers_periods p
        SET period_end = NEW.view_end_date,
            updated_at = now()
        WHERE p.notice_id = NEW.id
          AND p.period_start <= NEW.view_end_date
          AND (p.period_end IS NULL OR p.period_end > NEW.view_end_date);
    END IF;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_cfg_app_notices_limit_workers_periods
    ON public.cfg_app_notices;
CREATE TRIGGER trg_cfg_app_notices_limit_workers_periods
    AFTER UPDATE OF view_end_date ON public.cfg_app_notices
    FOR EACH ROW
    EXECUTE FUNCTION public.cfg_app_notices_limit_workers_periods();

-- 6. Trigger: bloqueia a gravação de lançamento fora da janela -----------
--    Aplicada no serviço via erro 'JANELA_ENCERRADA'/'JANELA_NAO_INICIADA'
--    (AppNoticesWorkersService). Esta trigger é a cadeia de validação
--    complementar no banco: se um processo tentar criar um período com
--    period_start fora da janela de visualização vigente, o banco rejeita.
--
--    ATENÇÃO (bug corrigido em 2026-10-20): tanto `period_start` quanto
--    `view_start_date`/`view_end_date` são `timestamp WITHOUT time zone` e
--    representam horário de São Paulo. A versão original declarava as
--    variáveis como `timestamptz`, o que forçava uma coerção dependente do
--    `TimeZone` da sessão: em sessões fora de America/Sao_Paulo a janela
--    deslocava 3h e o INSERT era rejeitado ("Período fora da janela"),
--    fazendo a unidade lançada sumir após o reload. Aqui usamos as MESMAS
--    colunas sem coerção — a comparação passa a ser naive vs. naive, igual
--    à do app (parseBrazilDate).
CREATE OR REPLACE FUNCTION public.cfg_app_notices_workers_periods_validate_janela()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    janela_inicio timestamp;   -- sem fuso: mesma natureza de period_start
    janela_fim    timestamp;   -- sem fuso: mesma natureza de period_start
BEGIN
    SELECT n.view_start_date, n.view_end_date
      INTO janela_inicio, janela_fim
      FROM public.cfg_app_notices n
     WHERE n.id = NEW.notice_id;

    IF janela_inicio IS NULL OR janela_fim IS NULL THEN
        -- janela não configurada no aviso: bloqueia a criação do período
        RAISE EXCEPTION 'Janela de visualização do aviso não configurada (view_start_date / view_end_date)';
    END IF;

    IF NEW.period_start < janela_inicio OR NEW.period_start >= janela_fim THEN
        RAISE EXCEPTION 'Período fora da janela de visualização do aviso (period_start = %, view_start_date = %, view_end_date = %)',
            NEW.period_start, janela_inicio, janela_fim;
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_cfg_app_notices_workers_periods_validate_janela
    ON public.cfg_app_notices_workers_periods;
CREATE TRIGGER trg_cfg_app_notices_workers_periods_validate_janela
    BEFORE INSERT OR UPDATE OF period_start ON public.cfg_app_notices_workers_periods
    FOR EACH ROW
    EXECUTE FUNCTION public.cfg_app_notices_workers_periods_validate_janela();

