-- ------------------------------------------------------------
-- 2. Guarda de imutabilidade das despesas
--    Após apropriação (ALLOCATED) ou fechamento (CLOSED) da
--    competência, nenhuma despesa pode entrar, sair ou mudar —
--    faça o estorno/reabra a competência antes de alterar.
--    (As RPCs nunca escrevem nesta tabela, então não há flag.)
-- ------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.fc_vehicle_monthly_expenses_guard() RETURNS trigger
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path TO 'public'
    AS $$
DECLARE
    v_status character varying;
BEGIN
    IF TG_OP <> 'DELETE' THEN
        SELECT p.status INTO v_status
        FROM public.vehicle_rental_periods p
        WHERE p.vehicle_id = NEW.vehicle_id
          AND p.reference_month = NEW.reference_month;

        IF v_status IN ('ALLOCATED', 'CLOSED') THEN
            RAISE EXCEPTION 'Despesas da competência % (veículo %) estão bloqueadas: período % — faça o estorno (fc_vehicle_rental_revert) ou reabra antes de alterar.',
                NEW.reference_month, NEW.vehicle_id, v_status;
        END IF;
    END IF;

    IF TG_OP <> 'INSERT' THEN
        SELECT p.status INTO v_status
        FROM public.vehicle_rental_periods p
        WHERE p.vehicle_id = OLD.vehicle_id
          AND p.reference_month = OLD.reference_month;

        IF v_status IN ('ALLOCATED', 'CLOSED') THEN
            RAISE EXCEPTION 'Despesas da competência % (veículo %) estão bloqueadas: período % — faça o estorno (fc_vehicle_rental_revert) ou reabra antes de alterar.',
                OLD.reference_month, OLD.vehicle_id, v_status;
        END IF;
    END IF;

    RETURN CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NEW END;
END;
$$;

DROP TRIGGER IF EXISTS trg_vehicle_monthly_expenses_guard ON public.vehicle_monthly_expenses;
CREATE TRIGGER trg_vehicle_monthly_expenses_guard
    BEFORE INSERT OR UPDATE OR DELETE ON public.vehicle_monthly_expenses
    FOR EACH ROW EXECUTE FUNCTION public.fc_vehicle_monthly_expenses_guard();

-- ------------------------------------------------------------
-- 3. Guard de linhas rateadas: 'rental', 'variable' E 'rate'
--    imutáveis fora das RPCs
--    (CREATE OR REPLACE com a MESMA assinatura — o trigger já
--     existente continua apontando para a função. Sem DROP.)
--    'rate' = linha de Km (odômetro) CONVERTIDA pela apuração:
--    mesmo id/value_total da linha original, congelada enquanto a
--    competência estiver alocada/fechada; o estorno a devolve a
--    'odometer' e a destrava.
-- ------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.fc_orders_visits_vehicles_rateio_guard() RETURNS trigger
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path TO 'public'
    AS $$
DECLARE
    v_flag boolean := coalesce(current_setting('app.vehicle_rental_write', true), '') = '1';
    v_status character varying;
    v_period_id bigint;
BEGIN
    IF TG_OP = 'INSERT' THEN
        -- Linhas de rateio/despesa/R$/km só nascem na apuração (RPC)
        IF v_flag THEN
            RETURN NEW;
        END IF;
        IF NEW.cost_type <> 'odometer' THEN
            RAISE EXCEPTION 'Linha de rateio (aluguel/despesa/R$/km) só pode ser criada pela apuração mensal (fc_vehicle_rental_*).';
        END IF;
        RETURN NEW;
    END IF;

    IF TG_OP = 'UPDATE' THEN
        -- Atualizações que não tocam em Km/valores são sempre permitidas
        -- (ex.: fc_sync_ov_costs_status espelha ov_costs_status da visita
        -- em todas as linhas filhas — incluindo linhas rateadas)
        IF NEW.ov_id IS NOT DISTINCT FROM OLD.ov_id
           AND NEW.vehicle_id IS NOT DISTINCT FROM OLD.vehicle_id
           AND NEW.recorder_start IS NOT DISTINCT FROM OLD.recorder_start
           AND NEW.recorder_end IS NOT DISTINCT FROM OLD.recorder_end
           AND NEW.amount IS NOT DISTINCT FROM OLD.amount
           AND NEW.discount IS NOT DISTINCT FROM OLD.discount
           AND NEW.cost_type IS NOT DISTINCT FROM OLD.cost_type
           AND NEW.is_deleted IS NOT DISTINCT FROM OLD.is_deleted THEN
            RETURN NEW;
        END IF;

        -- Linha de rateio (aluguel, despesa ou R$/km convertido):
        -- nunca editável fora da RPC
        IF NEW.cost_type IN ('rental', 'variable', 'rate') THEN
            IF v_flag THEN
                RETURN NEW;
            END IF;
            RAISE EXCEPTION 'Linha de rateio (aluguel/despesa/R$/km) é gerada pela apuração mensal e não pode ser editada.';
        END IF;

        -- Linha de odômetro já rateada: congelada até o estorno
        SELECT p.status, p.id INTO v_status, v_period_id
        FROM public.vehicles_rentals_allocations a
        JOIN public.vehicle_rental_periods p ON p.id = a.period_id
        WHERE a.ovv_id = NEW.id
        LIMIT 1;

        IF v_status IS NOT NULL AND NOT v_flag THEN
            RAISE EXCEPTION 'Km já rateado na competência % — faça o estorno (fc_vehicle_rental_revert) antes de alterar a leitura do odômetro.',
                v_period_id;
        END IF;

        RETURN NEW;
    END IF;

    -- DELETE ------------------------------------------------------------------
    IF OLD.cost_type IN ('rental', 'variable') THEN
        IF v_flag THEN
            RETURN OLD;
        END IF;

        SELECT p.status INTO v_status
        FROM public.vehicles_rentals_allocations a
        JOIN public.vehicle_rental_periods p ON p.id = a.period_id
        WHERE a.rental_ovv_id = OLD.id
        LIMIT 1;

        IF v_status = 'CLOSED' THEN
            RAISE EXCEPTION 'Competência fechada: o rateio (aluguel/despesa) é imutável (reabra a competência para alterar).';
        END IF;

        RETURN OLD;
    END IF;

    -- Linha de Km já rateada (ainda 'odometer' ou já convertida para
    -- 'rate'): bloqueia exclusão fora da RPC enquanto houver allocation
    SELECT p.status INTO v_status
    FROM public.vehicles_rentals_allocations a
    JOIN public.vehicle_rental_periods p ON p.id = a.period_id
    WHERE a.ovv_id = OLD.id
    LIMIT 1;

    IF v_status IS NOT NULL AND NOT v_flag THEN
        RAISE EXCEPTION 'Km já rateado — faça o estorno (fc_vehicle_rental_revert) antes de remover a linha do veículo.';
    END IF;

    RETURN OLD;
END;
$$;

-- ------------------------------------------------------------
-- 4. cost_type passa a aceitar 'rate'
--    'rate' = a MESMA linha de odômetro da visita depois de rateada
--    (mesmo id, amount, value_unit e value_total — a apuração apenas
--     troca a origem; o rollup soma todas as linhas, então ov_vehicles_value
--     não muda). DROP CONSTRAINT + ADD CONSTRAINT sem CASCADE: nenhum
--    objeto depende de uma CHECK constraint.
-- ------------------------------------------------------------
ALTER TABLE public.orders_visits_vehicles
    DROP CONSTRAINT IF EXISTS orders_visits_vehicles_cost_type_ck;

ALTER TABLE public.orders_visits_vehicles
    ADD CONSTRAINT orders_visits_vehicles_cost_type_ck
    CHECK (cost_type IN ('odometer', 'rental', 'variable', 'rate'));

-- ------------------------------------------------------------
-- 4.1 before_save: a conversão de origem não reprocessa a linha
--     O before_save da Fase 1 recalcula value_unit (de vehicles),
--     amount (odômetro) e value_total para tudo que não for
--     'rental'/'variable'. Se ele processasse a troca
--     'odometer' <-> 'rate', reescreveria o valor da linha (o total
--     cobrado deixaria de ser o de antes da alocação) e apagaria
--     as leituras do odômetro no estorno.
--     CREATE OR REPLACE com a MESMA assinatura (trigger aponta
--     para a função, não para o corpo).
-- ------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.fc_orders_visits_vehicles_before_save() RETURNS trigger
    LANGUAGE plpgsql
    SET search_path TO 'public'
    AS $$
DECLARE
    v_price numeric;
BEGIN

    -- Conversão de origem feita pela apuração (odometer <-> rate):
    -- só cost_type muda; amount/value_unit/value_total/recorder e
    -- desconto ficam intactos (o rollup recalcula o mesmo total).
    IF TG_OP = 'UPDATE'
       AND NEW.cost_type IS DISTINCT FROM OLD.cost_type
       AND NEW.ov_id IS NOT DISTINCT FROM OLD.ov_id
       AND NEW.vehicle_id IS NOT DISTINCT FROM OLD.vehicle_id
       AND NEW.recorder_start IS NOT DISTINCT FROM OLD.recorder_start
       AND NEW.recorder_end IS NOT DISTINCT FROM OLD.recorder_end
       AND NEW.amount IS NOT DISTINCT FROM OLD.amount
       AND NEW.discount IS NOT DISTINCT FROM OLD.discount
       AND NEW.is_deleted IS NOT DISTINCT FROM OLD.is_deleted THEN
        RETURN NEW;
    END IF;

    -- Linhas de rateio/despesa não têm odômetro: preserva amount/value_unit
    -- informados e recalcula apenas value_total.
    IF NEW.cost_type IN ('rental', 'variable') THEN
        NEW.recorder_start := NULL;
        NEW.recorder_end   := NULL;
        NEW.value_unit     := COALESCE(NEW.value_unit, 0);
        NEW.amount         := COALESCE(NEW.amount, 0);
        NEW.value_total    := ROUND(
            NEW.amount * NEW.value_unit * COALESCE(NEW.discount, 1), 2
        );
        RETURN NEW;
    END IF;

    -- Linha já convertida para 'rate': jamais recalcula (só a RPC de
    -- estorno devolve a 'odometer'; fora da flag o guard bloqueia)
    IF NEW.cost_type = 'rate' THEN
        RETURN NEW;
    END IF;

    SELECT value_unit
    INTO v_price
    FROM public.vehicles
    WHERE id = NEW.vehicle_id;

    NEW.value_unit := COALESCE(v_price,0);

    NEW.amount :=
        GREATEST(
            COALESCE(NEW.recorder_end,0)
            - COALESCE(NEW.recorder_start,0),
            0
        );

    NEW.value_total :=
        NEW.amount
        * NEW.value_unit
        * COALESCE(NEW.discount,1);

    RETURN NEW;

END;
$$;

-- ------------------------------------------------------------
-- 8.2 Resumo da competência (tabela da tela de Apuração)
--     + variable_value / variable_per_km
--     + operational_value / operational_per_km (componente R$/km:
--       soma das linhas de Km, sejam 'odometer' ou já convertidas
--       para 'rate' pelo allocate)
--     Gravado só em ALLOCATED/CLOSED (guard congela despesas/Km);
--     em OPEN e CALCULATED tudo é calculado ao vivo — depois de um
--     estorno o card senão mostraria as despesas de quando o cálculo
--     foi gravado.
--     DROP sem CASCADE (mudança de return type exige DROP; nenhum
--     caller no front-end nem no banco depende das colunas antigas).
-- ------------------------------------------------------------
DROP FUNCTION IF EXISTS public.fc_vehicle_rental_summary(date);

CREATE FUNCTION public.fc_vehicle_rental_summary(p_reference_month date)
RETURNS TABLE (
    period_id bigint,
    period_status character varying,
    vehicle_id bigint,
    vehicle_description text,
    vehicle_plates text,
    contract_id bigint,
    contract_value numeric,
    has_conflict boolean,
    total_km bigint,
    cost_per_km numeric,
    allocated_value numeric,
    idle_value numeric,
    utilization numeric,
    variable_value numeric,
    variable_per_km numeric,
    operational_value numeric,
    operational_per_km numeric
)
    LANGUAGE plpgsql STABLE SECURITY DEFINER
    SET search_path TO 'public'
    AS $$
DECLARE
    v_month date := (date_trunc('month', p_reference_month::timestamp))::date;
    v_month_end date := (date_trunc('month', p_reference_month::timestamp) + interval '1 month - 1 day')::date;
    v_row record;
    v_period public.vehicle_rental_periods%ROWTYPE;
    v_km bigint;
    v_rate numeric;
    v_rental_rate numeric;
    v_var_rate numeric;
    v_alloc numeric;
    v_alloc_rental numeric;
    v_alloc_variable numeric;
    v_value numeric;
    v_variable numeric;
    v_op numeric;
BEGIN
    FOR v_row IN
        WITH contract_info AS (
            SELECT c.vehicle_id,
                   count(*) AS n_contracts,
                   (array_agg(c.id ORDER BY c.start_date DESC, c.id DESC))[1] AS best_id,
                   (array_agg(c.monthly_value ORDER BY c.start_date DESC, c.id DESC))[1] AS best_value
            FROM public.cfg_vehicles_rentals_contracts c
            WHERE c.active AND NOT c.is_deleted
              AND c.start_date <= v_month_end
              AND (c.end_date IS NULL OR c.end_date >= v_month)
            GROUP BY c.vehicle_id
        ),
        base AS (
            SELECT u.vvehicle, u.vcid, u.vvalue, u.prio
            FROM (
                SELECT p.vehicle_id AS vvehicle, p.contract_id AS vcid,
                       p.contract_value AS vvalue, 0 AS prio
                FROM public.vehicle_rental_periods p
                WHERE p.reference_month = v_month
                UNION ALL
                SELECT ci.vehicle_id, ci.best_id, ci.best_value, 1
                FROM contract_info ci
            ) u
        )
        SELECT DISTINCT ON (b.vvehicle)
               b.vvehicle, b.vcid, b.vvalue,
               COALESCE(ci.n_contracts, 0) > 1 AS vconflict,
               ve.description AS vd, ve.plates AS vp
        FROM base b
        LEFT JOIN contract_info ci ON ci.vehicle_id = b.vvehicle
        JOIN public.vehicles ve ON ve.id = b.vvehicle AND NOT ve.is_deleted
        ORDER BY b.vvehicle, b.prio, ve.description
    LOOP
        SELECT p.* INTO v_period
        FROM public.vehicle_rental_periods p
        WHERE p.vehicle_id = v_row.vvehicle
          AND p.reference_month = v_month;

        -- Km total do mês (âncora: created_at da linha, fallback da visita).
        -- Conta linhas 'odometer' E 'rate' (a mesma linha depois de rateada).
        SELECT COALESCE(sum(ovv.amount), 0)::bigint,
               COALESCE(sum(ovv.value_total), 0)
        INTO v_km, v_op
        FROM public.orders_visits_vehicles ovv
        JOIN public.orders_visits ovs ON ovs.id = ovv.ov_id
        WHERE ovv.vehicle_id = v_row.vvehicle
          AND NOT ovv.is_deleted
          AND ovv.cost_type IN ('odometer', 'rate')
          AND ovv.amount > 0
          AND COALESCE(ovv.created_at, ovs.ov_created_at) >= v_month
          AND COALESCE(ovv.created_at, ovs.ov_created_at) < v_month + interval '1 month';

        v_value := COALESCE(v_period.contract_value, v_row.vvalue, 0);

        -- Despesas variáveis do mês (ao vivo; se o período já existe,
        -- o valor gravado no cálculo prevalece — ver IF abaixo)
        SELECT COALESCE(sum(e.value), 0)
        INTO v_variable
        FROM public.vehicle_monthly_expenses e
        WHERE e.vehicle_id = v_row.vvehicle
          AND e.reference_month = v_month;

        IF v_period.id IS NOT NULL THEN
            period_id := v_period.id;
            period_status := v_period.status;
        ELSE
            period_id := NULL;
            period_status := 'OPEN';
        END IF;

        IF v_period.id IS NOT NULL AND v_period.status IN ('ALLOCATED', 'CLOSED') THEN
            -- Competência confirmada/fechada: valores gravados são a
            -- fonte do rateio (o guard trava despesas e Km => gravado
            -- é idêntico ao ao vivo).
            total_km := v_period.total_km;
            v_rate := v_period.cost_per_km;
            v_alloc := v_period.allocated_value;
            v_variable := COALESCE(v_period.variable_value, 0);
        ELSE
            -- Prévia ao vivo: sem período, ou status CALCULATED (após
            -- estorno ou alocação interrompida). Nesse estado despesas
            -- e Km continuam editáveis, então usar o valor gravado no
            -- cálculo mostraria despesas desatualizadas no card.
            total_km := v_km;
            v_rate := CASE WHEN v_km > 0 THEN (v_value + v_variable) / v_km::numeric ELSE NULL END;
            v_rental_rate := CASE WHEN v_km > 0 THEN v_value / v_km::numeric ELSE NULL END;
            v_var_rate := CASE WHEN v_km > 0 AND v_variable > 0 THEN v_variable / v_km::numeric ELSE NULL END;

            -- Prévia: soma dos valores já arredondados por visita e por
            -- componente (mesma fórmula do fc_vehicle_rental_allocate)
            SELECT COALESCE(sum(round(ovv.amount * v_rental_rate, 2)), 0),
                   COALESCE(sum(round(ovv.amount * v_var_rate, 2)), 0)
            INTO v_alloc_rental, v_alloc_variable
            FROM public.orders_visits_vehicles ovv
            JOIN public.orders_visits ovs ON ovs.id = ovv.ov_id
            WHERE ovv.vehicle_id = v_row.vvehicle
              AND NOT ovv.is_deleted
              AND ovv.cost_type IN ('odometer', 'rate')
              AND ovv.amount > 0
              AND COALESCE(ovv.created_at, ovs.ov_created_at) >= v_month
              AND COALESCE(ovv.created_at, ovs.ov_created_at) < v_month + interval '1 month';

            v_alloc := v_alloc_rental + v_alloc_variable;
        END IF;

        vehicle_id := v_row.vvehicle;
        vehicle_description := v_row.vd;
        vehicle_plates := v_row.vp;
        contract_id := v_row.vcid;
        contract_value := v_value;
        has_conflict := v_row.vconflict;
        cost_per_km := v_rate;
        allocated_value := v_alloc;
        idle_value := (v_value + v_variable) - v_alloc;
        utilization := CASE
            WHEN (v_value + v_variable) > 0 THEN round(v_alloc / (v_value + v_variable), 4)
            ELSE NULL
        END;
        variable_value := v_variable;
        variable_per_km := CASE
            WHEN total_km > 0 AND v_variable > 0 THEN round(v_variable / total_km::numeric, 6)
            ELSE NULL
        END;
        operational_value := v_op;
        operational_per_km := CASE
            WHEN total_km > 0 THEN round(v_op / total_km::numeric, 6)
            ELSE NULL
        END;

        RETURN NEXT;
    END LOOP;
END;
$$;

