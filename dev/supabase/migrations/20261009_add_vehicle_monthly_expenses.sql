-- ------------------------------------------------------------
-- 1. Despesas variáveis mensais por veículo
--    Uma linha por lançamento (ex.: abastecimento, pedágio).
--    A soma do mês alimenta vehicle_rental_periods.variable_value
--    no cálculo da competência.
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.vehicle_monthly_expenses (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    vehicle_id bigint NOT NULL,
    reference_month date NOT NULL,
    cost_type_id bigint NOT NULL,
    value numeric(14,2) NOT NULL,
    description text,
    created_user_id bigint,
    created_at timestamp without time zone DEFAULT now(),
    updated_user_id bigint,
    updated_at timestamp without time zone,
    CONSTRAINT vehicle_monthly_expenses_pkey PRIMARY KEY (id),
    CONSTRAINT vehicle_monthly_expenses_month_ck
        CHECK (reference_month = date_trunc('month', reference_month)::date),
    CONSTRAINT vehicle_monthly_expenses_value_ck CHECK (value > 0),
    CONSTRAINT vehicle_monthly_expenses_vehicle_fk
        FOREIGN KEY (vehicle_id) REFERENCES public.vehicles (id) ON DELETE CASCADE,
    CONSTRAINT vehicle_monthly_expenses_type_fk
        FOREIGN KEY (cost_type_id) REFERENCES public.cfg_vehicles_costs_types (id)
);

COMMENT ON TABLE public.vehicle_monthly_expenses IS
