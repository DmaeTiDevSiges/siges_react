-- ============================================================
-- Migration: Rateio de Aluguel Veicular — Fase 2
-- Date: 2026-10-09
-- Description:
--   1) Despesas variáveis mensais REAIS (combustível, pedágio,
--      manutenção, seguro/IPVA, outros — tabela cfg_vehicles_costs_types
--      criada na Fase 1) passam a compor a apuração junto com o
--      aluguel do contrato.
--   2) Componente R$/km: a linha de odômetro (km × vehicles.value_unit)
--      da visita passa a ser CONVERTIDA na linha 'rate' do rateio
--      quando a competência é alocada — mesmo id, mesmo value_total,
--      logo o total cobrado na visita NÃO muda (só a origem/rótulo).
--
--   Base da Fase 2:
--     total          = aluguel do contrato + despesas do mês
--                      (+ R$/km op. × total_km, componente proporcional)
--     custo/km       = (aluguel + despesas) ÷ total_km  (total_km = 0 => NULL)
--     custo total/km = custo/km + R$/km op.
--     rateio/visita  = até 2 linhas: cost_component 'RENTAL' e
--                      'VARIABLE' (a 2ª só quando despesas > 0)
--                      + conversão da linha de Km em cost_type 'rate'
--     ociosidade     = (aluguel + despesas) − Σ rateios
--                      (o R$/km op. NÃO gera ociosidade: é 100% proporcional)
--     utilização     = apropriado ÷ (aluguel + despesas)
--
--   Conteúdo:
--     1. vehicle_monthly_expenses        (despesas do mês por veículo)
--     2. Trigger de guarda: despesas bloqueadas quando a competência
--        está ALLOCATED/CLOSED
--     3. Guard de linhas: cost_type 'variable' e 'rate' imutáveis
--        junto com 'rental' (CREATE OR REPLACE, mesma assinatura)
--     4. orders_visits_vehicles.cost_type ganha o valor 'rate'
--        (DROP CONSTRAINT + ADD CONSTRAINT, sem CASCADE) e
--        fc_orders_visits_vehicles_before_save deixa a troca de
--        origem 'odometer' <-> 'rate' passar sem recalcular valores
--     5. fc_vehicle_rental_summary  (+ variable_value, variable_per_km,
--        operational_value, operational_per_km)
--     6. fc_vehicle_rental_detail   (+ rental_value, variable_value,
--        variable_ovv_id, operational_value) — DROP + CREATE
--        (mudança de return type)
--     7. fc_vehicle_rental_calculate (soma despesas; conta Km de
--        linhas 'odometer' E 'rate')
--     8. fc_vehicle_rental_allocate  (2 componentes por visita +
--        converte a linha de Km em 'rate')
--     9. fc_vehicle_rental_revert    (recalcula com despesas vigentes
--        e devolve as linhas 'rate' para 'odometer')
--
--   Sem mudança em: fc_vehicle_rental_contract/_close/_reopen,
--   fc_financial_orders_visits_vehicles_sum (já agrupa por cost_type),
--   v_orders_visits_vehicles, before_save (já trata 'variable').
