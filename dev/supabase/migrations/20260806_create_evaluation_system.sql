-- 1. Tabela de Requisitos (Catálogo Geral)
CREATE TABLE IF NOT EXISTS public.cfg_evaluation_requirements (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    description character varying(255) NOT NULL,
    code character varying(50),
    is_available boolean DEFAULT true,
    is_deleted boolean DEFAULT false,
    created_at timestamp without time zone DEFAULT now(),
    updated_at timestamp without time zone DEFAULT now(),
    CONSTRAINT cfg_evaluation_requirements_pkey PRIMARY KEY (id),
    CONSTRAINT cfg_evaluation_requirements_code_key UNIQUE (code)
) TABLESPACE pg_default;

-- 2. Tabela de Vinculação Contrato × Requisito (com pontuação)
CREATE TABLE IF NOT EXISTS public.contracts_evaluation_requirements (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    contract_id bigint NOT NULL,
    evaluation_id bigint NOT NULL,
    weight integer NOT NULL,
    is_available boolean DEFAULT true,
    is_deleted boolean DEFAULT false,
    created_at timestamp without time zone DEFAULT now(),
    CONSTRAINT contracts_evaluation_requirements_pkey PRIMARY KEY (id),
    CONSTRAINT contracts_evaluation_requirements_contract_id_fkey FOREIGN KEY (contract_id)
        REFERENCES public.contracts (id) MATCH SIMPLE
        ON UPDATE NO ACTION
        ON DELETE CASCADE,
    CONSTRAINT contracts_evaluation_requirements_evaluation_id_fkey FOREIGN KEY (evaluation_id)
        REFERENCES public.cfg_evaluation_requirements (id) MATCH SIMPLE
        ON UPDATE NO ACTION
        ON DELETE CASCADE,
    CONSTRAINT contracts_evaluation_requirements_contract_evaluation_unique UNIQUE (contract_id, evaluation_id)
) TABLESPACE pg_default;

-- 3. Tabela de Avaliação da Visita
CREATE TABLE IF NOT EXISTS public.orders_visits_evaluations (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    ov_id bigint NOT NULL,
    contract_evaluation_id bigint NOT NULL,
    was_applied boolean NOT NULL DEFAULT false,
    notes text,
    evaluated_by_user_id bigint NOT NULL,
    evaluated_at timestamp without time zone DEFAULT now(),
    created_at timestamp without time zone DEFAULT now(),
    CONSTRAINT orders_visits_evaluations_pkey PRIMARY KEY (id),
    CONSTRAINT orders_visits_evaluations_ov_id_fkey FOREIGN KEY (ov_id)
        REFERENCES public.orders_visits (id) MATCH SIMPLE
        ON UPDATE NO ACTION
        ON DELETE CASCADE,
    CONSTRAINT orders_visits_evaluations_contract_evaluation_id_fkey FOREIGN KEY (contract_evaluation_id)
        REFERENCES public.contracts_evaluation_requirements (id) MATCH SIMPLE
        ON UPDATE NO ACTION
        ON DELETE CASCADE,
    CONSTRAINT orders_visits_evaluations_evaluated_by_user_id_fkey FOREIGN KEY (evaluated_by_user_id)
        REFERENCES public.users (id) MATCH SIMPLE
        ON UPDATE NO ACTION
        ON DELETE RESTRICT
) TABLESPACE pg_default;

-- 4. Índices
CREATE INDEX IF NOT EXISTS idx_contracts_evaluation_requirements_contract
    ON public.contracts_evaluation_requirements USING btree (contract_id) TABLESPACE pg_default;

CREATE INDEX IF NOT EXISTS idx_orders_visits_evaluations_ov
    ON public.orders_visits_evaluations USING btree (ov_id) TABLESPACE pg_default;

CREATE INDEX IF NOT EXISTS idx_orders_visits_evaluations_evaluated_by
    ON public.orders_visits_evaluations USING btree (evaluated_by_user_id) TABLESPACE pg_default;

-- 5. View de Avaliações da Visita
DROP VIEW IF EXISTS public.v_orders_visits_evaluations;

CREATE OR REPLACE VIEW public.v_orders_visits_evaluations AS
SELECT
    ove.id,
    ove.ov_id,
    ove.contract_evaluation_id,
    ove.was_applied,
    ove.notes,
    ove.evaluated_by_user_id,
    u.name_full AS evaluator_name,
    ove.evaluated_at,
    ove.created_at,
    -- Dados do requisito
    cer.contract_id,
    cer.weight,
    er.description AS requirement_description,
    er.code AS requirement_code
FROM public.orders_visits_evaluations ove
JOIN public.contracts_evaluation_requirements cer ON cer.id = ove.contract_evaluation_id
JOIN public.cfg_evaluation_requirements er ON er.id = cer.evaluation_id
JOIN public.users u ON u.id = ove.evaluated_by_user_id;

-- 6. View de Requisitos do Contrato
DROP VIEW IF EXISTS public.v_contracts_evaluation_requirements;

CREATE OR REPLACE VIEW public.v_contracts_evaluation_requirements AS
SELECT
    cer.id,
    cer.contract_id,
    cer.evaluation_id,
    cer.weight,
    cer.is_available,
    er.description AS evaluation_description,
    er.code AS evaluation_code
FROM public.contracts_evaluation_requirements cer
JOIN public.cfg_evaluation_requirements er ON er.id = cer.evaluation_id
WHERE cer.is_deleted = false AND er.is_deleted = false;
