-- Reverte 20261111_use_users_tracker_last_location.sql
-- Copia a última posição de volta para users, restaura fn_tracker_report_location
-- (gravando em users), volta users_tracker à estrutura legada e devolve o acesso
-- original de users_tracker (política "Universal Access" + GRANT ALL).
-- As linhas de users_tracker são mantidas.
BEGIN;

UPDATE public.users u
   SET latitude = t.latitude,
       longitude = t.longitude,
       tracker_accuracy = t.tracker_accuracy,
       tracked_at = t.tracked_at,
       tracker_heartbeat_at = t.tracker_heartbeat_at
  FROM public.users_tracker t
 WHERE t.user_id = u.id
   AND t.tracker_heartbeat_at IS NOT NULL;

CREATE OR REPLACE FUNCTION public.fn_tracker_report_location(
    p_token TEXT,
    p_latitude DOUBLE PRECISION,
    p_longitude DOUBLE PRECISION,
    p_accuracy DOUBLE PRECISION DEFAULT NULL
)
RETURNS TEXT
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
    v_token_id BIGINT;
    v_user_id BIGINT;
    v_is_available BOOLEAN;
    v_in_visit BOOLEAN;
    v_now TIMESTAMP WITHOUT TIME ZONE := timezone('America/Sao_Paulo', now());
BEGIN
    IF p_token IS NULL OR length(p_token) <> 64 THEN
        RETURN 'invalid';
    END IF;

    SELECT t.id, t.user_id INTO v_token_id, v_user_id
      FROM public.users_tracker_tokens t
     WHERE t.token_hash = encode(sha256(convert_to(p_token, 'UTF8')), 'hex')
       AND t.revoked_at IS NULL
     LIMIT 1;
    IF v_token_id IS NULL THEN
        RETURN 'invalid';
    END IF;

    IF p_latitude IS NULL OR p_longitude IS NULL
       OR p_latitude NOT BETWEEN -90 AND 90
       OR p_longitude NOT BETWEEN -180 AND 180
       OR (p_latitude = 0 AND p_longitude = 0) THEN
        RETURN 'rejected';
    END IF;

    -- Mesma regra do app (useLocationTracker/App.tsx): visita aberta =
    -- is_ov_in_progress OU ov_id_in_progress > 0.
    SELECT COALESCE(u.is_available, false),
           COALESCE(u.is_ov_in_progress, false) OR COALESCE(u.ov_id_in_progress, 0) > 0
      INTO v_is_available, v_in_visit
      FROM public.users u
     WHERE u.id = v_user_id;

    UPDATE public.users_tracker_tokens SET last_used_at = v_now WHERE id = v_token_id;

    -- Regra de rastreamento (LGPD): só enquanto disponível ou em visita.
    IF NOT (v_is_available OR v_in_visit) THEN
        RETURN 'paused';
    END IF;

    UPDATE public.users
       SET latitude = p_latitude,
           longitude = p_longitude,
           tracker_accuracy = CASE
               WHEN p_accuracy IS NULL OR p_accuracy < 0 THEN tracker_accuracy
               ELSE p_accuracy
           END,
           tracker_heartbeat_at = v_now,
           tracked_at = v_now
     WHERE id = v_user_id;

    RETURN 'ok';
END;
$$;

REVOKE ALL ON FUNCTION public.fn_tracker_report_location(TEXT, DOUBLE PRECISION, DOUBLE PRECISION, DOUBLE PRECISION) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.fn_tracker_report_location(TEXT, DOUBLE PRECISION, DOUBLE PRECISION, DOUBLE PRECISION) TO anon, authenticated;

DROP FUNCTION IF EXISTS public.fn_users_tracker_report_session(DOUBLE PRECISION, DOUBLE PRECISION, DOUBLE PRECISION);

-- Estrutura legada: id (PK identity), user_id, latitude, longitude, createddate, device.
ALTER TABLE public.users_tracker DROP CONSTRAINT IF EXISTS users_tracker_user_id_fkey;
ALTER TABLE public.users_tracker DROP CONSTRAINT IF EXISTS users_tracker_pkey;
ALTER TABLE public.users_tracker ADD COLUMN IF NOT EXISTS id BIGINT GENERATED BY DEFAULT AS IDENTITY;
ALTER TABLE public.users_tracker ADD COLUMN IF NOT EXISTS createddate TIMESTAMP WITH TIME ZONE;
ALTER TABLE public.users_tracker ADD COLUMN IF NOT EXISTS device VARCHAR;
UPDATE public.users_tracker SET createddate = tracked_at AT TIME ZONE 'America/Sao_Paulo' WHERE createddate IS NULL;
ALTER TABLE public.users_tracker ADD CONSTRAINT userstracks_pkey PRIMARY KEY (id);
ALTER TABLE public.users_tracker DROP COLUMN IF EXISTS tracker_heartbeat_at;
ALTER TABLE public.users_tracker DROP COLUMN IF EXISTS tracked_at;
ALTER TABLE public.users_tracker DROP COLUMN IF EXISTS tracker_accuracy;

DROP POLICY IF EXISTS users_tracker_select ON public.users_tracker;
DROP POLICY IF EXISTS "Universal Access" ON public.users_tracker;
CREATE POLICY "Universal Access" ON public.users_tracker USING (true) WITH CHECK (true);
GRANT ALL ON public.users_tracker TO anon, authenticated, service_role;

COMMIT;
