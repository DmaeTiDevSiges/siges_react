-- Migration: Contratos de R$/km (custo operacional por Km)
-- Date: 2026-10-10
-- Description:
--   O R$/km (custo operacional por Km) deixa de ser um valor estático
--   em vehicles.value_unit e passa a ser um CONTRATO COM VIGÊNCIA,
--   com o mesmo modelo dos contratos de aluguel:
--
--     • tabela cfg_vehicle_rate_contracts (veículo, R$/km, vigência,
--       ativo) — espelho de cfg_vehicles_rentals_contracts;
--     • fc_vehicle_rate_contract(vehicle_id, on_date) devolve o
--       contrato vigente NA DATA (mais recente vence; conflito se >1);
--     • o trigger fc_orders_visits_vehicles_before_save resolve o
--       preço da linha de odômetro pelo contrato vigente na data da
--     linha (created_at da linha; fallback: data da visita);
--     • informar Km em veículo SEM contrato vigente passa a ser
--       BLOQUEADO (amount > 0). amount = 0 (apenas adicionar o
--       veículo à visita) continua livre;
--     • vehicles.value_unit permanece como VALOR PADRÃO (origem do
--       import Manus) e é a fonte do backfill.
--
--   Semântica redefinida (documentada em UI/docs):
--     R$/km = custo OPERACIONAL por Km que NÃO inclui aluguel nem
--     despesas variáveis (combustível, pedágio, manutenção, seguro…
--     entram pela apuração como despesas do mês).
--
--   Backfill: todo veículo não-deletado recebe 1 contrato automático
--     • início = 1º dia do mês da 1ª linha de visita (ou 1º do mês
--       corrente, se o veículo ainda não tem visitas);
--     • fim    = 31/12/2026 (vigência encerra; depois disso um novo
--       contrato é exigido — a mensagem do trigger orienta);
--     • valor  = vehicles.value_unit atual.
--
--   Conteúdo:
--     1. cfg_vehicle_rate_contracts              (tabela + RLS/grants)
--     2. fc_vehicle_rate_contract(bigint, date)  (resolve por data)
--     3. Backfill automático de contratos        (idempotente)
--     4. fc_orders_visits_vehicles_before_save   (odometer usa o
--        contrato vigente na data; amount > 0 sem contrato ⇒ erro)
--     5. Rota transport_rate_contracts + grants
--
--   Aplicação MANUAL no SQL Editor do Supabase (regra do AGENTS.md),
--   DEPOIS de 20261008_create_vehicle_rental_rateio.sql e
--   20261009_add_vehicle_monthly_expenses.sql.
--   Idempotente: pode ser re-executada com segurança.
