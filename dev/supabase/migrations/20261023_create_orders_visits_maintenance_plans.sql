CREATE OR REPLACE FUNCTION public.approve_order_visit_with_maintenance_plans(
    p_visit_id bigint,
    p_user_id bigint,
    p_order_status_id bigint,
    p_progress double precision,
    p_suspended_reason_id bigint DEFAULT NULL,
    p_cause_reason_id bigint DEFAULT NULL
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    v_order_id bigint;
    v_current_status_id bigint;
    v_ended_at timestamp without time zone;
    v_authenticated_user_id bigint;
    v_now timestamp without time zone := timezone('America/Sao_Paulo', now());
BEGIN
    SELECT id INTO v_authenticated_user_id
    FROM public.users
    WHERE uuid = auth.uid();

    IF auth.uid() IS NULL OR v_authenticated_user_id IS DISTINCT FROM p_user_id THEN
        RAISE EXCEPTION 'Usuário não autorizado para aprovar a visita';
    END IF;

    IF p_progress IS NULL OR p_progress < 0 OR p_progress > 100 THEN
        RAISE EXCEPTION 'Progresso inválido para aprovação da visita';
    END IF;

    SELECT ov.o_id, ov.ov_ended_at
    INTO v_order_id, v_ended_at
    FROM public.orders_visits ov
    WHERE ov.id = p_visit_id
      AND COALESCE(ov.is_deleted, false) = false
    FOR UPDATE;

    IF NOT FOUND OR v_order_id IS NULL THEN
        RAISE EXCEPTION 'Visita não encontrada ou sem ordem associada';
    END IF;

    SELECT o.status_id
    INTO v_current_status_id
    FROM public.orders o
    WHERE o.id = v_order_id
      AND COALESCE(o.is_deleted, false) = false
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Ordem de serviço não encontrada';
    END IF;

    IF v_current_status_id IS DISTINCT FROM 5 THEN
        UPDATE public.orders
        SET status_id = p_order_status_id,
            status_at = v_ended_at,
            progress = CASE WHEN p_order_status_id = 8 THEN 1 ELSE p_progress / 100.0 END,
            cause_reason_id = COALESCE(p_cause_reason_id, cause_reason_id),
            updated_user_id = p_user_id,
            updated_at = v_now
        WHERE id = v_order_id;
    END IF;

    UPDATE public.orders_visits
    SET ov_processing_id = 5,
        ov_approved_user_id = p_user_id,
        ov_approved_at = v_now,
        ov_o_status_id = p_order_status_id,
        ov_o_progress = CASE WHEN p_order_status_id = 8 THEN 1 ELSE p_progress / 100.0 END,
        ov_o_suspended_reason_id = CASE WHEN p_order_status_id = 6 THEN p_suspended_reason_id ELSE NULL END,
        updated_user_id = p_user_id,
        updated_at = v_now
    WHERE id = p_visit_id;

    INSERT INTO public.orders_visits_maintenances_plans (o_id, ov_id, maintenance_plan_id)
    SELECT DISTINCT v_order_id, p_visit_id, ova.maintenance_plan_id
    FROM public.orders_visits_assets ova
    WHERE ova.ov_id = p_visit_id
      AND COALESCE(ova.is_deleted, false) = false
      AND ova.processing_id IN (2, 3, 5)
      AND ova.maintenance_plan_id > 0
    ON CONFLICT (ov_id, maintenance_plan_id) DO NOTHING;
END;
$$;

CREATE OR REPLACE FUNCTION public.reverse_order_visit_approval(
    p_visit_id bigint
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    v_authenticated_user_id bigint;
    v_now timestamp without time zone := timezone('America/Sao_Paulo', now());
BEGIN
    SELECT id INTO v_authenticated_user_id
    FROM public.users
    WHERE uuid = auth.uid();

    IF auth.uid() IS NULL OR v_authenticated_user_id IS NULL THEN
        RAISE EXCEPTION 'Usuário não autenticado para reverter aprovação da visita';
    END IF;

    PERFORM 1
    FROM public.orders_visits
    WHERE id = p_visit_id
      AND ov_processing_id = 5
      AND COALESCE(is_deleted, false) = false
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Visita aprovada não encontrada';
    END IF;

    UPDATE public.orders_visits_assets
    SET processing_id = 2
    WHERE ov_id = p_visit_id;

    UPDATE public.orders_visits
    SET ov_processing_id = 2,
        ov_assets_approved_no_filed_amount = 0,
        ov_approved_at = NULL,
        ov_approved_user_id = NULL,
        ov_costs_status = 'pending',
        ov_costs_waiting_at = NULL,
        ov_costs_approved_at = NULL,
        ov_costs_rejected_at = NULL,
        ov_costs_rejection_reason = NULL,
        updated_user_id = v_authenticated_user_id,
        updated_at = v_now
    WHERE id = p_visit_id;

    DELETE FROM public.orders_visits_maintenances_plans
    WHERE ov_id = p_visit_id;
END;
$$;

