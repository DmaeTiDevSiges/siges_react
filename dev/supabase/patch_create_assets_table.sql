-- Create assets table
create table if not exists public.assets (
  id bigint generated by default as identity not null,
  company_id bigint null,
  unit_id bigint null,
  code character varying null,
  description text null,
  status_id bigint null,
  tag_id bigint null,
  tag_sub_id bigint null,
  status_at timestamp without time zone null,
  type_id bigint null,
  searchable text null,
  comments text null,
  brand character varying null,
  model character varying null,
  serial character varying null,
  power numeric null,
  power_unit character varying null,
  voltage character varying null,
  amperage character varying null,
  poles smallint null,
  voltage_unit character varying null,
  amperage_unit character varying null,
  poles_unit character varying null,
  rotation integer null,
  rotation_unit character varying null,
  service_factor numeric null default '1'::numeric,
  pressure_max numeric null,
  pressure_min numeric null,
  pressure_operation numeric null,
  pressure_unit character varying null,
  flow_rate_max numeric null,
  flow_rate_min numeric null,
  flow_rate_operation numeric null,
  flow_rate_unit character varying null,
  rotor_diameter numeric null,
  rotor_diameter_unit character varying null,
  priority_id smallint null default '3'::smallint,
  material_id bigint null,
  material_code character varying null,
  acquisition_at timestamp without time zone null,
  location character varying null,
  weight numeric null,
  weight_unit character varying null,
  created_user_id bigint not null default '1'::bigint,
  created_at timestamp without time zone null default now(),
  updated_user_id bigint null,
  updated_at timestamp without time zone null,
  is_deleted boolean null default false,
  deleted_user_id bigint null,
  deleted_at timestamp without time zone null,
  coupling_model_id smallint null,
  acquisition_value numeric null default '0'::numeric,
  version_mode character varying null default 'live'::character varying,
  img_file_path character varying null,
  img_file_name character varying null,
  unit_asset_tag_id bigint null,
  company_owner_id bigint null default '1'::bigint,
  img_file_name_thumb character varying null,
  client_id bigint null,
  constraint assets_pkey primary key (id),
  constraint assets_id_key unique (id),
  -- constraint assets_unit_asset_tag_id_fkey foreign KEY (unit_asset_tag_id) references cfg_units_assets_tags (id), -- Table cfg_units_assets_tags not found
  constraint assets_unit_id_fkey foreign KEY (unit_id) references units (id),
  constraint assets_type_id_fkey foreign KEY (type_id) references cfg_assets_types (id),
  constraint assets_company_owner_id_fkey foreign KEY (company_owner_id) references cfg_companies (id),
  constraint assets_company_id_fkey foreign KEY (company_id) references cfg_companies (id) on update CASCADE
) TABLESPACE pg_default;

-- Enable RLS
alter table public.assets enable row level security;

-- Policies
create policy "Public read access" on public.assets for select using (true);
create policy "Authenticated insert" on public.assets for insert with check (auth.role() = 'authenticated');
create policy "Authenticated update" on public.assets for update using (auth.role() = 'authenticated');
create policy "Authenticated delete" on public.assets for delete using (auth.role() = 'authenticated');
