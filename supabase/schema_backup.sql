-- Notifications Count
CREATE OR REPLACE FUNCTION public.handle_notifications_count()
RETURNS trigger AS $$
BEGIN
  IF (TG_OP = 'INSERT') THEN
    IF (NEW.is_read = false) THEN
      UPDATE public.users SET notifications_amount = COALESCE(notifications_amount, 0) + 1 WHERE id = NEW.user_id;
    END IF;
  ELSIF (TG_OP = 'UPDATE') THEN
    IF (OLD.is_read = false AND NEW.is_read = true) THEN
      UPDATE public.users SET notifications_amount = GREATEST(COALESCE(notifications_amount, 0) - 1, 0) WHERE id = NEW.user_id;
    ELSIF (OLD.is_read = true AND NEW.is_read = false) THEN
      UPDATE public.users SET notifications_amount = COALESCE(notifications_amount, 0) + 1 WHERE id = NEW.user_id;
    END IF;
  ELSIF (TG_OP = 'DELETE') THEN
    IF (OLD.is_read = false) THEN
      UPDATE public.users SET notifications_amount = GREATEST(COALESCE(notifications_amount, 0) - 1, 0) WHERE id = OLD.user_id;
    END IF;
  END IF;
  RETURN NULL;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

DROP TRIGGER IF EXISTS on_notifications_count ON public.users_notifications;
CREATE TRIGGER on_notifications_count
  AFTER INSERT OR UPDATE OR DELETE ON public.users_notifications
  FOR EACH ROW EXECUTE PROCEDURE public.handle_notifications_count();

-- Profile Photo Notification
CREATE OR REPLACE FUNCTION public.handle_profile_photo_change_notification()
RETURNS trigger AS $$
BEGIN
  IF (OLD.img_file_name IS DISTINCT FROM NEW.img_file_name) AND (NEW.img_file_name IS NOT NULL) THEN
    INSERT INTO public.users_notifications (user_id, related_user_id, title, message, type)
    SELECT u.id, NEW.id, 'Foto de perfil atualizada', 'Usuário ' || COALESCE(NEW.name_full, 'Desconhecido') || ' atualizou a foto de perfil', 'profile_photo_change'
    FROM public.users u WHERE u.is_admin_super = true;
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

DROP TRIGGER IF EXISTS on_profile_photo_change ON public.users;
CREATE TRIGGER on_profile_photo_change
  AFTER UPDATE OF img_file_name ON public.users
  FOR EACH ROW EXECUTE PROCEDURE public.handle_profile_photo_change_notification();

